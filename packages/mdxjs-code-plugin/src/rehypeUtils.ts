import type { MdxJsxFlowElementHast } from "mdast-util-mdx-jsx";
import type { MdxjsEsmHast } from "mdast-util-mdxjs-esm";
import * as acorn from "acorn";
import { fromMarkdown } from "mdast-util-from-markdown";
import { mdxJsxFromMarkdown } from "mdast-util-mdx-jsx";
import { mdxjsEsmFromMarkdown } from "mdast-util-mdxjs-esm";
import { mdxJsx } from "micromark-extension-mdx-jsx";
import { mdxjsEsm } from "micromark-extension-mdxjs-esm";

export function createMdxjsEsmNode(ecmaScript: string): MdxjsEsmHast {
    const tree = fromMarkdown(ecmaScript, {
        extensions: [mdxjsEsm({ acorn, addResult: true })],
        mdastExtensions: [mdxjsEsmFromMarkdown()]
    });

    const node = firstChild(tree) as MdxjsEsmHast;
    quoteStringNames(node);
    return node;
}

/**
 * The code generated by mdx-js expects the imported name of a specifier to be an identifier, turning a string name
 * into `undefined`. An identifier is printed as is, so give it the source of the string.
 */
function quoteStringNames(node: MdxjsEsmHast) {
    for (const statement of node.data?.estree?.body ?? []) {
        if (statement.type === "ImportDeclaration") {
            for (const specifier of statement.specifiers) {
                if (specifier.type === "ImportSpecifier" && specifier.imported.type === "Literal") {
                    specifier.imported = { type: "Identifier", name: String(specifier.imported.raw) };
                }
            }
        }
    }
}

export function createMdxJsxFlowElement(jsx: string): MdxJsxFlowElementHast {
    const tree = fromMarkdown(jsx, {
        extensions: [mdxJsx({ acorn, addResult: true })],
        mdastExtensions: [mdxJsxFromMarkdown()]
    })

    return firstChild(tree) as MdxJsxFlowElementHast;
}

function firstChild(tree: ReturnType<typeof fromMarkdown>) {
    const node = tree.children[0];
    if (!node) {
        throw new Error("expected the source to produce a node");
    }
    return node;
}
